def arithmetic_progression(begin, step, end=None):
    """generator for a progression from begin to end (None means no end), for the given step"""
    result = type(begin + step)(begin)
    forever = end is None
    index = 0
    while forever or result < end:
        yield result
        index += 1
        result = begin + step * index
