def main():
    lang = "Italian"

    if lang == "English":
        print("Welcome!")
    elif lang == "Spanish":
        print("¡Bienvenido!")
    elif lang == "French":
        print("Bienvenue!")
    elif lang == "Italian":
        print("Benvenuto!")


if __name__ == "__main__":
    main()
